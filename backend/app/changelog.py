def seed_changelog(db: Session) -> None:
    existing = {(e.version, e.title): e for e in db.scalars(select(ChangelogEntry))}
    for rel in RELEASES:
        when = datetime.strptime(rel["date"], "%Y-%m-%d %H:%M").replace(tzinfo=CN)
        for category, title, detail in rel["entries"]:
            e = existing.get((rel["version"], title))
            if e is None:
                db.add(ChangelogEntry(version=rel["version"], released_at=when, category=category, title=title, detail=detail))
            elif e.released_at is not None and e.released_at.astimezone(CN).replace(second=0, microsecond=0) != when:
                # 发布时间以代码为准（更正写错的时间后，线上也跟着改）
                e.released_at = when
            if e is not None and (e.detail != detail or e.category != category):
                e.detail, e.category = detail, category  # 正文和分类也以代码为准（改措辞后线上跟着改）
    db.commit()
